#!/usr/bin/env python3
"""Download the two self-hosted font families (Newsreader, Inter) as woff2.

Build-time script. Fetches the Google Fonts CSS with a modern-browser user
agent, keeps only latin blocks, downloads each woff2 into site/assets/fonts/,
and writes site/assets/fonts.css with local @font-face rules. Also saves each
family's OFL licence next to the files. After this runs once and the files are
committed, the site makes no remote font calls.

Run:  python3 scripts/fetch_fonts.py
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEST = os.path.join(HERE, "site", "assets", "fonts")
UA = ("Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) "
      "Chrome/124.0 Safari/537.36")

CSS_URL = ("https://fonts.googleapis.com/css2?family=Newsreader:opsz,wght@6..72,400"
           "&family=Inter:wght@100..900&display=swap")
LICENCES = {
    "newsreader": "https://raw.githubusercontent.com/google/fonts/main/ofl/newsreader/OFL.txt",
    "inter": "https://raw.githubusercontent.com/google/fonts/main/ofl/inter/OFL.txt",
}


def curl(url):
    r = subprocess.run(["curl", "-sSL", "--max-time", "60", "-A", UA, url],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit("curl failed for %s: %s" % (url, r.stderr[:200]))
    return r.stdout


def main():
    os.makedirs(DEST, exist_ok=True)
    css = curl(CSS_URL)
    blocks = re.findall(r"/\* (\w+) \*/\s*(@font-face\s*\{[^}]+\})", css)
    if not blocks:
        raise SystemExit("no @font-face blocks in the served CSS")
    out = ["/* Self-hosted fonts, generated by scripts/fetch_fonts.py.",
           "   Sources: Newsreader and Inter, SIL Open Font License 1.1 (files in this directory). */", ""]
    kept = 0
    for subset, block in blocks:
        if "U+0000-00FF" not in block:      # latin block only
            continue
        fam = re.search(r"font-family:\s*'([^']+)'", block).group(1).lower()
        weight = re.search(r"font-weight:\s*([0-9 ]+);", block).group(1).strip()
        style = re.search(r"font-style:\s*(\w+)", block).group(1)
        url = re.search(r"url\((https://fonts\.gstatic\.com/[^)]+\.woff2)\)", block).group(1)
        name = "%s-%s-%s.woff2" % (fam, weight.replace(" ", "-"), style)
        path = os.path.join(DEST, name)
        if not os.path.exists(path):
            data = subprocess.run(["curl", "-sSL", "--max-time", "60", "-o", path, url],
                                  capture_output=True)
            if data.returncode != 0 or os.path.getsize(path) < 1000:
                raise SystemExit("download failed for " + url)
        out.append("@font-face {")
        out.append("  font-family: '%s';" % fam.capitalize())
        out.append("  font-style: %s;" % style)
        out.append("  font-weight: %s;" % weight)
        out.append("  font-display: swap;")
        out.append("  src: url('assets/fonts/%s') format('woff2');" % name)
        out.append("  unicode-range: %s;" % re.search(r"unicode-range:\s*([^;]+);", block).group(1))
        out.append("}")
        out.append("")
        kept += 1
    with open(os.path.join(HERE, "site", "assets", "fonts.css"), "w") as f:
        f.write("\n".join(out) + "\n")
    for name, url in LICENCES.items():
        lic = curl(url)
        if "SIL OPEN FONT LICENSE" not in lic.upper():
            raise SystemExit("licence fetch for %s did not look like OFL" % name)
        with open(os.path.join(DEST, name + "-OFL.txt"), "w") as f:
            f.write(lic)
    print("font files kept:", kept)
    for fn in sorted(os.listdir(DEST)):
        print(" ", fn, os.path.getsize(os.path.join(DEST, fn)), "bytes")


if __name__ == "__main__":
    main()
